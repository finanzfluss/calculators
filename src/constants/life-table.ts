export const LIFE_TABLE_MAX_AGE = 100

function survivors(qx: number[]) {
  const lx = [100_000]
  for (let age = 1; age <= LIFE_TABLE_MAX_AGE; age++) {
    lx.push(lx[age - 1]! * (1 - qx[age - 1]!))
  }
  return lx
}

const LX_MALE = survivors(QX_MALE)
const LX_FEMALE = survivors(QX_FEMALE)

/** Probability that a person aged `fromAge` reaches `toAge` (both 0–100). */
export function survivalProbability(fromAge: number, toAge: number) {
  return {
    female: LX_FEMALE[toAge]! / LX_FEMALE[fromAge]!,
    male: LX_MALE[toAge]! / LX_MALE[fromAge]!,
  }
}
